<?php
/**
 * The scripts and styles of diagrams, from `build/`.
 *
 * @package MermaidBlocks
 */

namespace MermaidBlocks;

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Registers the Mermaid library, and the script and style that turn diagram
 * markup into SVGs.
 *
 * - `mermaid-js`: the Mermaid library, for the editor.
 * - `mermaid-blocks-diagram` (script): renders each diagram on the page when
 *   it scrolls into view, and adds its controls. It loads Mermaid's ES module
 *   build from `build/mermaid/` on demand, so Mermaid isn't one of its
 *   dependencies.
 * - `mermaid-blocks-diagram` (style): hides the source until it renders, and
 *   styles the controls.
 */
final class Assets {

	/**
	 * The handle of the Mermaid library.
	 */
	const MERMAID = 'mermaid-js';

	/**
	 * The handle of the script, and of the style, that render diagrams.
	 */
	const RENDERER = 'mermaid-blocks-diagram';

	/**
	 * The main file of the plugin.
	 *
	 * @var string
	 */
	private string $plugin_file;

	/**
	 * Sets up the assets.
	 *
	 * @param string $plugin_file The main file of the plugin.
	 */
	public function __construct( string $plugin_file ) {
		$this->plugin_file = $plugin_file;
	}

	/**
	 * Registers the assets with WordPress.
	 */
	public function hooks(): void {
		// Before the block, which refers to them by handle, at the default priority.
		add_action( 'init', array( $this, 'register' ), 9 );
	}

	/**
	 * Returns the path of a file the build generated.
	 *
	 * @param string $file Optional. The file, relative to `build/`.
	 *
	 * @return string The path. Without a file, the path of `build/`.
	 */
	public function get_path( string $file = '' ): string {
		return plugin_dir_path( $this->plugin_file ) . 'build/' . $file;
	}

	/**
	 * Returns the URL of a file the build generated.
	 *
	 * @param string $file Optional. The file, relative to `build/`.
	 *
	 * @return string The URL. Without a file, the URL of `build/`.
	 */
	public function get_url( string $file = '' ): string {
		return plugin_dir_url( $this->plugin_file ) . 'build/' . $file;
	}

	/**
	 * Reads an asset file generated by the build.
	 *
	 * @param string $name Entry name, such as `view` for `build/view.asset.php`.
	 *
	 * @return array Dependencies and version of the built file.
	 */
	public function get_build_asset( string $name ): array {
		$asset_file = $this->get_path( "{$name}.asset.php" );
		$asset      = file_exists( $asset_file ) ? include $asset_file : array();

		return wp_parse_args(
			$asset,
			array(
				'dependencies' => array(),
				'version'      => false,
			)
		);
	}

	/**
	 * Registers the Mermaid library, and the script and style that render
	 * diagrams.
	 */
	public function register(): void {
		$mermaid = $this->get_build_asset( 'mermaid' );
		wp_register_script(
			self::MERMAID,
			$this->get_url( 'mermaid.min.js' ),
			array(),
			$mermaid['version'],
			true
		);

		$view = $this->get_build_asset( 'view' );
		wp_register_script(
			self::RENDERER,
			$this->get_url( 'view.js' ),
			$view['dependencies'],
			$view['version'],
			true
		);

		// The script has no dependencies, so its few labels are translated here.
		$settings = array(
			'mermaidUrl' => add_query_arg( 'ver', $mermaid['version'], $this->get_url( 'mermaid/mermaid.esm.min.js' ) ),
			'i18n'       => array(
				'controls'      => __( 'Diagram controls', 'mermaid-blocks' ),
				'zoomIn'        => __( 'Zoom in', 'mermaid-blocks' ),
				'zoomOut'       => __( 'Zoom out', 'mermaid-blocks' ),
				'resetZoom'     => __( 'Reset zoom', 'mermaid-blocks' ),
				'downloadSvg'   => __( 'Download as SVG', 'mermaid-blocks' ),
				'downloadPng'   => __( 'Download as PNG', 'mermaid-blocks' ),
				'downloadError' => __( 'The file could not be created.', 'mermaid-blocks' ),
			),
		);
		wp_add_inline_script(
			self::RENDERER,
			'var mermaidBlocksSettings = ' . wp_json_encode( $settings ) . ';',
			'before'
		);

		$style_file = $this->get_path( 'style-index.css' );
		wp_register_style(
			self::RENDERER,
			$this->get_url( 'style-index.css' ),
			array(),
			file_exists( $style_file ) ? (string) filemtime( $style_file ) : false
		);

		// Same handling WordPress gives stylesheets declared as files in block.json.
		$rtl_style_file = $this->get_path( 'style-index-rtl.css' );
		if ( is_rtl() && file_exists( $rtl_style_file ) ) {
			wp_style_add_data( self::RENDERER, 'rtl', 'replace' );
			wp_style_add_data( self::RENDERER, 'path', $rtl_style_file );
		} else {
			wp_style_add_data( self::RENDERER, 'path', $style_file );
		}
	}

	/**
	 * Enqueues the script and style that render diagrams on the page.
	 */
	public function enqueue_renderer(): void {
		wp_enqueue_script( self::RENDERER );
		wp_enqueue_style( self::RENDERER );
	}
}
