<?php
/**
 * Diagram rendering shared by the block and any other integration, such as
 * a shortcode or a page builder widget.
 *
 * An integration outputs mermaid_blocks_get_diagram_markup() and makes sure
 * the `mermaid-blocks-diagram` script and style are loaded: the function
 * enqueues them, and an integration that renders outside a normal page load
 * declares both handles as its dependencies instead. Diagrams added to the
 * page later, such as a widget a page builder re-renders in its preview, are
 * rendered by calling `window.mermaidBlocks.render( element )`.
 *
 * A diagram whose wrapper has a `data-mermaid-controls` attribute gets controls
 * for visitors: `zoom`, `download`, or both, separated by a space.
 *
 * @package MermaidBlocks
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Reads an asset file generated by the build.
 *
 * @param string $name Entry name, such as `view` for `build/view.asset.php`.
 *
 * @return array Dependencies and version of the built file.
 */
function mermaid_blocks_get_build_asset( $name ) {
	$asset_file = plugin_dir_path( MERMAID_BLOCKS_PLUGIN_FILE ) . "build/{$name}.asset.php";
	$asset      = file_exists( $asset_file ) ? include $asset_file : array();

	return wp_parse_args(
		$asset,
		array(
			'dependencies' => array(),
			'version'      => false,
		)
	);
}

/**
 * Registers the Mermaid library, and the script and style that turn diagram
 * markup into SVGs.
 *
 * - `mermaid-js`: the Mermaid library, for the editor.
 * - `mermaid-blocks-diagram` (script): renders each diagram on the page when
 *   it scrolls into view, and adds its controls. It loads Mermaid's ES module
 *   build from `build/mermaid/` on demand, so Mermaid isn't one of its
 *   dependencies.
 * - `mermaid-blocks-diagram` (style): hides the source until it renders, and
 *   styles the controls.
 */
function mermaid_blocks_register_diagram_assets() {
	$build_dir = plugin_dir_path( MERMAID_BLOCKS_PLUGIN_FILE ) . 'build/';
	$build_url = plugin_dir_url( MERMAID_BLOCKS_PLUGIN_FILE ) . 'build/';

	$mermaid = mermaid_blocks_get_build_asset( 'mermaid' );
	wp_register_script(
		'mermaid-js',
		$build_url . 'mermaid.min.js',
		array(),
		$mermaid['version'],
		true
	);

	$view = mermaid_blocks_get_build_asset( 'view' );
	wp_register_script(
		'mermaid-blocks-diagram',
		$build_url . 'view.js',
		$view['dependencies'],
		$view['version'],
		true
	);

	// The script has no dependencies, so its few labels are translated here.
	$settings = array(
		'mermaidUrl' => add_query_arg( 'ver', $mermaid['version'], $build_url . 'mermaid/mermaid.esm.min.js' ),
		'i18n'       => array(
			'controls'      => __( 'Diagram controls', 'mermaid-blocks' ),
			'zoomIn'        => __( 'Zoom in', 'mermaid-blocks' ),
			'zoomOut'       => __( 'Zoom out', 'mermaid-blocks' ),
			'resetZoom'     => __( 'Reset zoom', 'mermaid-blocks' ),
			'downloadSvg'   => __( 'Download as SVG', 'mermaid-blocks' ),
			'downloadPng'   => __( 'Download as PNG', 'mermaid-blocks' ),
			'downloadError' => __( 'The file could not be created.', 'mermaid-blocks' ),
		),
	);
	wp_add_inline_script(
		'mermaid-blocks-diagram',
		'var mermaidBlocksSettings = ' . wp_json_encode( $settings ) . ';',
		'before'
	);

	$style_file = $build_dir . 'style-index.css';
	wp_register_style(
		'mermaid-blocks-diagram',
		$build_url . 'style-index.css',
		array(),
		file_exists( $style_file ) ? (string) filemtime( $style_file ) : false
	);

	// Same handling WordPress gives stylesheets declared as files in block.json.
	$rtl_style_file = $build_dir . 'style-index-rtl.css';
	if ( is_rtl() && file_exists( $rtl_style_file ) ) {
		wp_style_add_data( 'mermaid-blocks-diagram', 'rtl', 'replace' );
		wp_style_add_data( 'mermaid-blocks-diagram', 'path', $rtl_style_file );
	} else {
		wp_style_add_data( 'mermaid-blocks-diagram', 'path', $style_file );
	}
}
add_action( 'init', 'mermaid_blocks_register_diagram_assets', 9 );

/**
 * Enqueues the script and style that render diagrams on the page.
 */
function mermaid_blocks_enqueue_diagram_assets() {
	wp_enqueue_script( 'mermaid-blocks-diagram' );
	wp_enqueue_style( 'mermaid-blocks-diagram' );
}

/**
 * Returns the diagram source, escaped for the page.
 *
 * Output it as the content of an element with the `mermaid-blocks-diagram`
 * class. mermaid_blocks_get_diagram_markup() does both.
 *
 * - The source stays inside a <pre>: wptexturize and convert_smilies run
 *   over post content and would turn `-->` into an en dash and straight
 *   quotes into curly quotes everywhere except inside <pre> and <code>.
 * - esc_textarea() is used instead of esc_html(): esc_html() does not
 *   double-encode, so a literal `&amp;` or `&lt;` typed by the user would
 *   come back from `textContent` as `&` or `<`. esc_textarea() double-encodes,
 *   so `textContent` equals the source exactly.
 * - Square brackets are output as numeric entities: do_shortcode() also runs
 *   over post content, so a node such as `A[gallery]` or `B[audio]` would be
 *   replaced by the shortcode's output. The browser decodes the entities back
 *   to brackets before the renderer reads the source.
 *
 * @param string $code Mermaid source.
 *
 * @return string The `<pre>` element holding the source.
 */
function mermaid_blocks_get_diagram_source_markup( $code ) {
	$source = str_replace(
		array( '[', ']' ),
		array( '&#91;', '&#93;' ),
		esc_textarea( (string) $code )
	);

	return '<pre class="mermaid-blocks-diagram__source">' . $source . '</pre>';
}

/**
 * Returns the markup of a diagram, and enqueues the assets that render it.
 *
 * For integrations other than the block. The block wraps
 * mermaid_blocks_get_diagram_source_markup() itself, to keep the wrapper
 * attributes the block editor adds.
 *
 * @param string $code       Mermaid source.
 * @param array  $attributes Optional. Extra attributes for the wrapper
 *                           element, as name => value. A `class` is added to
 *                           the `mermaid-blocks-diagram` class, and
 *                           `data-mermaid-controls` lists the controls visitors
 *                           get: `zoom`, `download`, or `zoom download`.
 *
 * @return string The diagram markup, or an empty string when there is no code.
 */
function mermaid_blocks_get_diagram_markup( $code, $attributes = array() ) {
	$code = (string) $code;

	if ( '' === trim( $code ) ) {
		return '';
	}

	$class               = isset( $attributes['class'] ) ? $attributes['class'] : '';
	$attributes['class'] = trim( 'mermaid-blocks-diagram ' . $class );

	$attribute_markup = '';
	foreach ( $attributes as $name => $value ) {
		if ( ! preg_match( '/^[a-zA-Z_:][a-zA-Z0-9_:.-]*$/', (string) $name ) ) {
			continue;
		}

		$attribute_markup .= sprintf( ' %s="%s"', $name, esc_attr( $value ) );
	}

	mermaid_blocks_enqueue_diagram_assets();

	return '<div' . $attribute_markup . '>' . mermaid_blocks_get_diagram_source_markup( $code ) . '</div>';
}
